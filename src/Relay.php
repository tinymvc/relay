<?php

namespace Spark\Relay;

use Pusher\Pusher;
use RuntimeException;
use function config;
use function is_array;
use function json_encode;

class Relay
{
    private ?Pusher $client = null;

    public function __construct(
        private ?App $app = null,
        private ?array $clientConfig = null
    ) {
    }

    /**
     * Lazily initialize and return the Pusher PHP SDK client.
     */
    public function client(): Pusher
    {
        if ($this->client !== null) {
            return $this->client;
        }

        $app = $this->resolveApp();
        $cfg = $this->resolveClientConfig();

        $scheme = (string) ($cfg['scheme'] ?? 'http');
        $useTls = $scheme === 'https';

        $options = [
            'host' => (string) ($cfg['host'] ?? '127.0.0.1'),
            'port' => (int) ($cfg['port'] ?? 8080),
            'scheme' => $scheme,
            'useTLS' => $useTls,
            'timeout' => (int) ($cfg['timeout'] ?? 5),
            'cluster' => 'mt1',
        ];

        $this->client = new Pusher(
            $app->key,
            $app->secret,
            $app->appId,
            $options
        );

        return $this->client;
    }

    /**
     * Trigger an event on one or more channels.
     *
     * @param array|string $channels
     * @param string $event
     * @param array|string $data
     * @param string|null $socketId
     * @return mixed
     */
    public function trigger(array|string $channels, string $event, array|string $data, ?string $socketId = null): mixed
    {
        $params = $socketId !== null ? ['socket_id' => $socketId] : [];
        return $this->client()->trigger($channels, $event, $data, $params);
    }

    /**
     * Authorize a private or presence channel for a socket connection.
     * Returns the exact JSON string generated by the Pusher SDK.
     *
     * @param string $channel
     * @param string $socketId
     * @param array|null $presence Array with 'id' (or 'user_id') and optional 'info'
     * @return string
     */
    public function authorize(string $channel, string $socketId, ?array $presence = null): string
    {
        $customData = null;
        if ($presence !== null) {
            $userId = (string) ($presence['id'] ?? $presence['user_id'] ?? '');
            $userInfo = $presence['info'] ?? $presence['user_info'] ?? [];
            $customData = json_encode([
                'user_id' => $userId,
                'user_info' => $userInfo,
            ], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        }

        return $this->client()->authorizeChannel($channel, $socketId, $customData);
    }

    private function resolveApp(): App
    {
        if ($this->app !== null) {
            return $this->app;
        }

        $rawApps = config('relay.apps', []);
        if (!is_array($rawApps) || empty($rawApps)) {
            throw new RuntimeException('No Relay applications configured in config/relay.php.');
        }

        $first = reset($rawApps);
        $this->app = App::fromConfig($first);

        return $this->app;
    }

    private function resolveClientConfig(): array
    {
        if ($this->clientConfig !== null) {
            return $this->clientConfig;
        }

        $cfg = config('relay.client', []);
        return is_array($cfg) ? $cfg : [];
    }
}
